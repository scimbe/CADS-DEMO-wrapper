#!/usr/bin/env node
// Copies the pure conversion modules of the new app (scimbe/CADS-agent-marketplace apps/mdi/src) into lib/vendor/mdi, so the
// server reads a free card out of a v2 link with exactly the code the app runs: one implementation, not two.
//
//   node bin/vendor-mdi.mjs <checkout>/apps/mdi/src [--track feat/mdi-paritaet]
//
// What is copied: every card whose module exports toFree (cards/<id>/card.js, found by importing it), the app's gate
// projection (features/frei/doc.js: gateView, gateChecksOf), the app's link decoder (app/link.js: decode, encode, MAX_FRAGMENT,
// with its generated Ajv validators gen/validators.js), and everything those import (contract/, engines/, manifests and
// JSON data), at the same relative paths. The app's harness already keeps cards/ and engines/ free of DOM, clock, network and
// globals; test/vendor-mdi.test.mjs imports the copy with those globals booby-trapped to make sure.
// Generated: index.js (the registry: CARDS by id, gateView, gateChecksOf, decode, encode, MAX_FRAGMENT). PROVENANCE.json pins the commit, every file's
// sha256 and a hash over the whole bundle. test/vendor-mdi.test.mjs refuses a copy that was edited or is incomplete, and,
// with MDI_SRC pointing at a checkout (CI job vendor-drift), a copy that drifted from the app.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const DIR = fileURLToPath(new URL('../lib/vendor/mdi/', import.meta.url));
export const REPO = 'scimbe/CADS-agent-marketplace';
export const MODULES = ['features/frei/doc.js', 'app/link.js'];   // besides the cards: the app's gate projection and link decoder

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
/** One hash over the whole bundle: sorted "path sha256" lines. */
export const bundleHash = (files) => sha(Object.keys(files).sort().map((f) => `${f} ${files[f]}\n`).join(''));

/** Relative imports of a module (static, re-exports, JSON with import attributes). A bare import is an error: nothing outside src. */
export function importsOf(text, file) {
  const out = [];
  for (const m of text.matchAll(/(?:^|[\s;])(?:import|export)\s[^'"`;]*?from\s*["']([^"']+)["']|(?:^|[\s;])import\s*["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)/g)) {
    const p = m[1] || m[2] || m[3];
    if (!p.startsWith('./') && !p.startsWith('../')) throw new Error(`bare import "${p}" in ${file}: not vendorable`);
    out.push(p);
  }
  return out;
}
/** Every file the entries need, relative to src, sorted. Throws on a path that leaves src. */
export function closureOf(src, entries) {
  const seen = new Set();
  const walk = (rel) => {
    if (seen.has(rel)) return;
    const abs = resolve(src, rel);
    if (relative(src, abs).startsWith('..')) throw new Error(`import leaves src: ${rel}`);
    seen.add(rel);
    if (!rel.endsWith('.js')) return;
    for (const p of importsOf(readFileSync(abs, 'utf8'), rel)) walk(relative(src, resolve(dirname(abs), p)).split('\\').join('/'));
  };
  for (const e of entries) walk(e);
  return [...seen].sort();
}
/** The cards of the app that hand a free card over (toFree), found by importing each card module. */
export async function freeCards(src) {
  const ids = [];
  for (const id of readdirSync(join(src, 'cards')).sort()) {
    const f = join(src, 'cards', id, 'card.js');
    if (!existsSync(f)) continue;
    const m = await import(pathToFileURL(f));
    if (m.default && typeof m.default.toFree === 'function') ids.push(id);
  }
  return ids;
}
/** The generated registry. */
export function indexSource(cards) {
  const name = (id) => 'c_' + id.replace(/-/g, '_');
  return '// GENERATED by bin/vendor-mdi.mjs from apps/mdi/src - do not edit. Provenance: PROVENANCE.json.\n'
    + cards.map((id) => `import ${name(id)} from './cards/${id}/card.js';\n`).join('')
    + "export { gateView, gateChecksOf } from './features/frei/doc.js';\n"
    + "export { decode, encode, MAX_FRAGMENT } from './app/link.js';\n"
    + `export const CARDS = Object.freeze({ ${cards.map((id) => `'${id}': ${name(id)}`).join(', ')} });\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), ti = args.indexOf('--track');
  const track = ti >= 0 ? args.splice(ti, 2)[1] : 'feat/mdi-paritaet';
  const src = resolve(args[0] || '');
  if (!existsSync(join(src, 'cards'))) { console.error('usage: node bin/vendor-mdi.mjs <checkout>/apps/mdi/src [--track <branch>]'); process.exit(2); }
  const commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const dirty = execFileSync('git', ['-C', src, 'status', '--porcelain', '--', '.'], { encoding: 'utf8' }).trim();
  if (dirty) { console.error('uncommitted changes in the app source:\n' + dirty); process.exit(1); }
  const cards = await freeCards(src);
  const list = closureOf(src, [...cards.map((id) => `cards/${id}/card.js`), ...MODULES]);
  rmSync(DIR, { recursive: true, force: true });
  const files = {};
  for (const rel of list) {
    mkdirSync(dirname(join(DIR, rel)), { recursive: true });
    copyFileSync(join(src, rel), join(DIR, rel));
    files[rel] = sha(readFileSync(join(DIR, rel)));
  }
  writeFileSync(join(DIR, 'index.js'), indexSource(cards));
  files['index.js'] = sha(readFileSync(join(DIR, 'index.js')));
  const prov = { repo: REPO, path: 'apps/mdi/src', track, commit, generatedBy: 'bin/vendor-mdi.mjs', cards, modules: MODULES, bundle: bundleHash(files), files };
  writeFileSync(join(DIR, 'PROVENANCE.json'), JSON.stringify(prov, null, 2) + '\n');
  console.log(`vendored ${list.length} files (+ index.js) for ${cards.length} cards from ${commit.slice(0, 12)} (${track}), bundle ${prov.bundle.slice(0, 12)}`);
}

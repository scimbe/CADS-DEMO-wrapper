export function germanizeReport(html) {
  // Fallback first: its sentences are replaced as a whole, and the claim of authorship goes.
  html = html.replace(/This week(?:'|&#39;)s briefing highlights the ([^<]+?)\.(?=\s*<|\s*$)/, (_, list) => {
    let s = list.split(' and the ').map((p) => p.replace(/^(.+?) of /, '$1: ')).join(', ');
    for (const [en, de] of LOWER) s = s.split(en).join(de);
    return `Das Sprachmodell hat diesmal keinen prüfbaren Text geliefert. Die wichtigsten Kennzahlen: ${s}.`;
  });
  html = html.replace(/the narrative text above was written by\s*<code>[^<]*\(fallback template, guard failed\)<\/code>\s*selecting and phrasing these figures under an enforced facts-only guard\s*&mdash; note: the LLM output failed the guard on this run, so the narrative\s*above is the deterministic fallback sentence, not model-written prose/,
    'der Text oben ist diesmal ein fester Ersatzsatz aus den Kennzahlen, weil das Sprachmodell die Prüfung nicht bestanden hat');
  for (const [en, de] of DE_MAP) html = html.split(en).join(de);
  return html.replace(/([A-Za-zÄÖÜäöü]+) Weekly Weather Briefing/g, 'Wöchentliches Wetter-Briefing $1').replace(/([A-Za-zÄÖÜäöü]+) (\d+)-Day Weather Briefing/g, 'Wetter-Briefing $1 ($2 Tage)').replace(/(\d(?:\.\d)?)days/g, '$1 Tage').replace(/lang="en"/g, 'lang="de"');
}

/** What the run says about its own text: the page must not call a fallback sentence a model's work. */
export function readRunOutcome(outDir) {
  const p = join(outDir, 'run-manifest.json');
  if (!existsSync(p)) return { known: false, fallback: false, reason: '' };
  try { const m = JSON.parse(readFileSync(p, 'utf8')); return { known: true, fallback: m.llm_fallback_used === true, reason: String(m.guard_reason || '') }; }
  catch { return { known: false, fallback: false, reason: '' }; }
}

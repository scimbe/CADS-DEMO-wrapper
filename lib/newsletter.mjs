// newsletter: what the wrapper changes around the signed bundle, and what it reads back from a run.
// The bundle is pinned by sha256 in the manifest and in the signed template, so fixes that belong to
// its source (CADS-DEMO-newsletter) are applied to the unpacked copy of a run, like patchWaiter in
// lib/timeline.mjs. Patches return null on unexpected source, so the caller can report that.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const PARSE_LINE = '    narrative = str(data["narrative"])';
const PARSE_PATCH = `    narrative = data.get("narrative")
    if not isinstance(narrative, str):  # wrapper patch: the local model writes "narr"/"narrual" for this key
        narrative = next((v for k, v in data.items() if k != "selected_highlight_ids" and isinstance(v, str)), "")
    if not narrative.strip():
        raise KeyError("narrative")`;
/** The German prompt makes the local model misspell the key (6 of 6 calls), which ended in the fallback. */
export function patchParser(src) {
  return src.includes(PARSE_LINE) ? src.replace(PARSE_LINE, PARSE_PATCH) : null;
}

const GUARD_LINE = '    for match in _NUMBER_RE.finditer(narrative):';
/** "11,8" was read as the two numbers 11 and 8, so an invented "31,10" passed as day and month. */
export function patchGuard(src) {
  if (!src.includes(GUARD_LINE) || src.includes('German decimal')) return null;
  return src.replace(GUARD_LINE, `    narrative = re.sub(r"(?<=\\d),(?=\\d)", ".", narrative)  # wrapper patch: German decimal comma\n${GUARD_LINE}`);
}

const COUNTRY = { Wien: 'AT', 'Zürich': 'CH' };
/** config/report.yaml for the chosen place and period. `coords` = [lat, lon, tz] of a known place. */
export function reportConfigPatch(y, { location, coords, days } = {}) {
  if (location && coords) {
    const [lat, lon, tz] = coords;
    y = y.replace(/name:\s*".*"/, `name: "${location}, ${COUNTRY[location] || 'DE'}"`).replace(/latitude:\s*[\d.]+/, `latitude: ${lat}`).replace(/longitude:\s*[\d.]+/, `longitude: ${lon}`).replace(/timezone:\s*".*"/, `timezone: "${tz}"`);
  }
  if (days) y = y.replace(/days:\s*\d+/, `days: ${days}`);
  const place = (location && coords) ? location : (y.match(/report_title:\s*"(.+?) (?:Weekly|\d+-Day) Weather Briefing"/) || [])[1];
  const n = Number((y.match(/days:\s*(\d+)/) || [])[1]);
  if (place) y = y.replace(/report_title:\s*".*"/, `report_title: "${place} ${n === 7 || !n ? 'Weekly' : n + '-Day'} Weather Briefing"`);
  return y;
}


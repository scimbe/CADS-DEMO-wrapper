const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);
/** t(key, vars?) -> string for `lang`; falls back to German, then to the key itself. */
export const makeT = (lang) => {
  const l = normLang(lang);
  return (key, vars) => fill(UI[l][key] ?? UI.de[key] ?? key, vars);
};
/** The `js.*`, `status.*`, `search.*` and `pb.*` subset, shipped to the browser as JSON for client-side messages. */
export const clientStrings = (lang) => {
  const l = normLang(lang);
  const out = {};
  for (const k of Object.keys(UI.de)) if (k.startsWith('js.') || k.startsWith('status.') || k.startsWith('search.') || k.startsWith('pb.')) out[k] = UI[l][k] ?? UI.de[k];
  return out;
};
